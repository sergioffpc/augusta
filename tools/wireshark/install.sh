#!/bin/bash
# Installs the augusta dissector (ADR-0076) for the user running it: copies
# augusta.lua into Wireshark's personal Lua plugins folder, and adds the
# protocol's schema directory to the default profile's Protobuf search paths,
# with "Load all files" on. Safe to run again: it replaces the shim and never
# adds the search path twice.
#
# Usage:
#   tools/wireshark/install.sh
#
# Runs on Linux, macOS and Git Bash on Windows. WIRESHARK_CONFIG_DIR, which
# Wireshark itself honours, picks another personal configuration folder.

set -euo pipefail

# Whether this shell runs on Windows (Git Bash).
on_windows() {
  case "$(uname -s)" in
    MINGW* | MSYS* | CYGWIN*) return 0 ;;
    *) return 1 ;;
  esac
}

# Prints Wireshark's personal configuration folder, where the default
# profile's files live, as Wireshark looks for it (wsutil/filesystem.c).
config_dir() {
  if [[ -n "${WIRESHARK_CONFIG_DIR:-}" ]]; then
    echo "${WIRESHARK_CONFIG_DIR}"
  elif on_windows; then
    echo "$(cygpath -u "${APPDATA}")/Wireshark"
  else
    # The XDG folder, unless only the older ~/.wireshark exists.
    local -r xdg="${XDG_CONFIG_HOME:-${HOME}/.config}/wireshark"
    if [[ ! -d "${xdg}" && -d "${HOME}/.wireshark" ]]; then
      echo "${HOME}/.wireshark"
    else
      echo "${xdg}"
    fi
  fi
}

# Prints Wireshark's personal Lua plugins folder.
# Arguments:
#   The personal configuration folder.
plugins_dir() {
  if on_windows; then
    echo "$1/plugins"
  else
    echo "${HOME}/.local/lib/wireshark/plugins"
  fi
}

# Prints a path as Wireshark reads it: on Windows, a native path with forward
# slashes, which its UAT files need no escaping for.
# Arguments:
#   The path.
wireshark_path() {
  if on_windows; then
    cygpath -m "$1"
  else
    echo "$1"
  fi
}

# Adds a directory to a protobuf_search_paths UAT file with "Load all files"
# on, replacing every row of the same directory already there.
# Arguments:
#   The UAT file, then the directory as Wireshark reads it.
add_search_path() {
  local -r uat="$1"
  local -r row="\"$2\",\"TRUE\""
  if [[ ! -f "${uat}" ]]; then
    # The header Wireshark writes, so the file reads as one it saved.
    {
      echo "# This file is automatically generated. BE CAREFUL MODIFYING."
      echo "#\"Protobuf source directory\",\"Load all files\""
    } >"${uat}"
  fi
  local -r others="$(grep -vF -- "\"$2\"," "${uat}" || true)"
  {
    if [[ -n "${others}" ]]; then
      echo "${others}"
    fi
    echo "${row}"
  } >"${uat}"
}

main() {
  local -r tool_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
  local -r schema_dir="$(cd "${tool_dir}/../../src/modules/protocol/proto" && pwd)"
  local -r config="$(config_dir)"
  local -r plugins="$(plugins_dir "${config}")"

  mkdir -p "${config}" "${plugins}"
  cp "${tool_dir}/augusta.lua" "${plugins}/augusta.lua"
  echo "Installed ${plugins}/augusta.lua"

  add_search_path "${config}/protobuf_search_paths" \
    "$(wireshark_path "${schema_dir}")"
  echo "Protobuf search path ${schema_dir} in ${config}/protobuf_search_paths"
}

main "$@"
